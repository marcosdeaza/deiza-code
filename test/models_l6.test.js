assert.strictEqual(c.normalizeModel('liquid-5.1'), 'deiza-liquid-5.1');
assert.throws(() => c.normalizeModel('liquid-6'), /13 de noviembre/);
assert.throws(() => c.normalizeModel('deiza-liquid-6'), /13 de noviembre/);
